import { format, resolveConfig } from 'prettier';
const formatting = await resolveConfig('src/generated/guidance.ts');
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const ids = ['wishos', 'wishos-system', 'wishos-drivers', 'wishos-applications', 'wishos-packages'];
const layers = ['overview', 'system', 'drivers', 'applications', 'packages'];
const records = await Promise.all(
  ids.map(async (id, i) => {
    const file = `skills/${id}/SKILL.md`,
      text = await readFile(file, 'utf8');
    return {
      id,
      layer: layers[i],
      uri: `wishos://skills/${id}`,
      mimeType: 'text/markdown',
      sha256: createHash('sha256').update(text).digest('hex'),
      source: { repository: 'https://github.com/cccat6/WishOS-Hub', path: file },
      text,
    };
  }),
);
await mkdir('src/generated', { recursive: true });
await writeFile(
  'src/generated/guidance.ts',
  await format(
    '// Generated by scripts/build-guidance.mjs from versioned skill sources.\nexport const guidance = ' +
      JSON.stringify(records, null, 2) +
      ' as const;\n',
    { ...formatting, parser: 'typescript' },
  ),
);

const authoringFile = 'skills/wishos-applications/references/authoring-checklist.md';
const authoringText = await readFile(authoringFile, 'utf8');
const guidanceReferences = [
  {
    id: 'application-checklist',
    uri: 'wishos://skills/wishos-applications/references/authoring-checklist',
    mimeType: 'text/markdown',
    sha256: createHash('sha256').update(authoringText).digest('hex'),
    source: { repository: 'https://github.com/cccat6/WishOS-Hub', path: authoringFile },
    text: authoringText,
  },
];
await writeFile(
  'src/generated/guidance-references.ts',
  await format(
    '// Generated from versioned Hub skill references.\nexport const guidanceReferences = ' +
      JSON.stringify(guidanceReferences, null, 2) +
      ' as const;\n',
    { ...formatting, parser: 'typescript' },
  ),
);

const snapshot = JSON.parse(await readFile('vendor/os-reference/snapshot.json', 'utf8'));
const references = await Promise.all(
  snapshot.files.map(async (record) => {
    const text = await readFile(`vendor/os-reference/${record.file ?? record.id + '.md'}`, 'utf8');
    if (createHash('sha256').update(text).digest('hex') !== record.sha256)
      throw Error('OS reference snapshot changed: ' + record.id);
    return {
      ...record,
      mimeType: record.mimeType ?? 'text/markdown',
      uri: `wishos://references/${record.id}`,
      source: { repository: snapshot.repository, commit: snapshot.commit, path: record.path },
      text,
    };
  }),
);
await writeFile(
  'src/generated/os-references.ts',
  await format(
    '// Generated from a pinned OS source snapshot.\nexport const osReferences = ' +
      JSON.stringify(references, null, 2) +
      ' as const;\n',
    { ...formatting, parser: 'typescript' },
  ),
);
